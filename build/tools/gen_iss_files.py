"""Generates installer/payload_files.iss from FROZEN_MANIFEST.tsv (or the manifest given as argument 1): one [Files] line per payload file
(BeforeInstall backup + AfterInstall SHA256 check) and the list of payload sub-folders for [Code]."""
import os, sys
REL = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAN = sys.argv[1] if len(sys.argv) > 1 else os.path.join(REL, 'config', 'FROZEN_MANIFEST.tsv')   # optional: manifest of a new build
rows = [l.rstrip('\n').split('\t') for l in open(MAN, encoding='utf-8')][1:]
assert all("'" not in r[0] and '"' not in r[0] for r in rows)
dirs = sorted({os.path.dirname(r[0]) for r in rows} - {''})
alldirs = sorted({'\\'.join(d.split('\\')[:i]) for d in dirs for i in range(1, d.count('\\') + 2)})
out = ['; GENERATED by tools\\gen_iss_files.py from FROZEN_MANIFEST.tsv - do not edit by hand',
       '#define PayloadCount %d' % len(rows), '', '[Files]']
for path, size, sha in rows:
    d = os.path.dirname(path)
    out.append('Source: "{#Payload}\\%s"; DestDir: "{code:ModKh2Dir}%s"; Flags: ignoreversion; '
               "BeforeInstall: BackupIfNeeded('%s'); AfterInstall: VerifyFile('%s', True)"
               % (path, '\\' + d if d else '', sha, sha))
out += ['', '[Code]', 'procedure AddPayloadDirs(L: TStringList);', 'begin']
out += ["  L.Add('%s');" % d for d in alldirs]
out += ['end;', '']
open(os.path.join(REL, 'installer', 'payload_files.iss'), 'w', encoding='utf-8', newline='\r\n').write('\n'.join(out))
print('files', len(rows), 'dirs', len(alldirs))
